export function catalogChain(chainId: number): ChainRecord | undefined {
  return CHAIN_CATALOG.find((chain) => chain.chainId === chainId);
}

/** The chains of one environment, in catalog order. */
export function catalogChainsOfEnv(testnet: boolean): ChainRecord[] {
  return CHAIN_CATALOG.filter((chain) => chain.testnet === testnet);
}
